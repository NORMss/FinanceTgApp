"""Метки операции: «отпуск», «ремонт», «подарки».

Метка отвечает на вопрос «в рамках чего», а категория — «на что». Разница не
академическая: отпуск размазан по такси, кафе, жилью и развлечениям, и вычесть его
из отчёта исключением категорий невозможно — вместе с отпуском уедет вся обычная
жизнь в тех же категориях.

Хранятся плоской строкой через запятую (`Transaction.tags`). Нормализация нужна,
чтобы «Отпуск», «отпуск » и «ОТПУСК» были одной меткой: иначе фильтр находит треть
трат, а человек уверен, что пометил все.
"""

MAX_TAGS = 12
MAX_TAG = 32


def parse_tags(raw: str) -> list[str]:
    """Строка -> список меток: без пустых, без дублей, в нижнем регистре."""
    seen: list[str] = []
    for piece in (raw or "").split(","):
        tag = " ".join(piece.split()).lower()[:MAX_TAG]
        if tag and tag not in seen:
            seen.append(tag)
    return seen[:MAX_TAGS]


def normalize_tags(raw: str) -> str:
    """Приводит строку меток к каноничному виду — ровно в таком она ложится в базу."""
    return ",".join(parse_tags(raw))
